#!/usr/bin/env node
// Generates the "Supported services" table in README.md from the compiled
// registry, between the markers below. Run directly or via `npm run registry:build`
// (which calls updateReadmeServices). `--check` exits 1 if README.md is stale.
//
//   node scripts/readme-services.mjs [--check]

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const START_MARKER = '<!-- services:start (generated by scripts/readme-services.mjs, do not edit) -->';
export const END_MARKER = '<!-- services:end -->';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const TRAINS = { yes: 'Yes', conditional: 'Sometimes', no: 'No', unknown: 'Unclear' };
const DEFAULTS = {
  opted_in: 'On',
  opted_out: 'Off',
  no_choice: 'No choice',
  varies_by_region: 'Varies by region',
  not_applicable: 'n/a',
};
const OPT_OUT_TYPES = {
  toggle: 'Setting',
  form: 'Web form',
  email: 'Request letter',
  'account-deletion': 'Delete account',
  none: 'None available',
};
const CONFIDENCE_RANK = { high: 3, medium: 2, experimental: 1 };

/** Escape text for a Markdown table cell. */
export function cell(text) {
  return String(text ?? '')
    .replace(/\\/g, '\\\\')
    .replace(/\|/g, '\\|')
    .replace(/[\r\n]+/g, ' ')
    .trim();
}

/**
 * Markdown table (unformatted) for a list of registry services.
 * @param {object[]} services compiled registry services (already sorted by name)
 */
export function renderServicesTable(services) {
  const header = [
    'Service',
    'Company',
    'Trains on your data',
    'Default',
    'Ways to opt out',
    'Automated',
    'Last verified',
  ];
  const rows = services.map((s) => {
    const types = [...new Set((s.optOuts ?? []).map((o) => OPT_OUT_TYPES[o.type] ?? o.type))];
    const best = (s.optOuts ?? [])
      .map((o) => o.automation?.confidence)
      .filter(Boolean)
      .sort((a, b) => (CONFIDENCE_RANK[b] ?? 0) - (CONFIDENCE_RANK[a] ?? 0))[0];
    return [
      `[${cell(s.name)}](registry/services/${s.id}.json)`,
      cell(s.company),
      cell(TRAINS[s.training?.trainsOnUserData] ?? s.training?.trainsOnUserData),
      cell(DEFAULTS[s.training?.defaultState] ?? s.training?.defaultState),
      cell(types.join(', ')),
      best ? `Yes (${best})` : 'No',
      cell(s.lastVerified),
    ];
  });
  const lines = [
    `| ${header.join(' | ')} |`,
    `| ${header.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.join(' | ')} |`),
  ];
  return lines.join('\n');
}

/** The full generated block (markers included), formatted with Prettier when available. */
export async function renderServicesSection(services) {
  const automated = services.filter((s) => (s.optOuts ?? []).some((o) => o.automation)).length;
  let table = renderServicesTable(services);
  try {
    const prettier = await import('prettier');
    const options = (await prettier.resolveConfig(path.join(ROOT, 'README.md'))) ?? {};
    table = (await prettier.format(table, { ...options, parser: 'markdown' })).trimEnd();
  } catch {
    // Prettier is a devDependency; without it the table is still valid Markdown.
  }
  return [
    START_MARKER,
    '',
    `${services.length} services, ${automated} with one-click automation. "Default: On" means the service trains on your data unless you opt out.`,
    '',
    table,
    '',
    END_MARKER,
  ].join('\n');
}

/**
 * Replace the generated section of a README text.
 * @returns {string|null} new text, or null if the markers are missing
 */
export function replaceSection(readme, section) {
  const start = readme.indexOf(START_MARKER);
  const end = readme.indexOf(END_MARKER);
  if (start === -1 || end === -1 || end < start) return null;
  return readme.slice(0, start) + section + readme.slice(end + END_MARKER.length);
}

/**
 * Update (or with check: verify) README.md in `root`.
 * @returns {Promise<{ status: 'updated'|'unchanged'|'outdated'|'missing'|'no-markers', file: string }>}
 */
export async function updateReadmeServices({ root = ROOT, services, check = false } = {}) {
  const file = path.join(root, 'README.md');
  let readme;
  try {
    readme = await readFile(file, 'utf8');
  } catch {
    return { status: 'missing', file };
  }
  const next = replaceSection(readme, await renderServicesSection(services));
  if (next === null) return { status: 'no-markers', file };
  if (next === readme) return { status: 'unchanged', file };
  if (check) return { status: 'outdated', file };
  await writeFile(file, next);
  return { status: 'updated', file };
}

async function main() {
  const check = process.argv.includes('--check');
  const registryFile = path.join(ROOT, 'registry', 'dist', 'registry.json');
  const registry = JSON.parse(await readFile(registryFile, 'utf8'));
  const result = await updateReadmeServices({ services: registry.services, check });
  const rel = path.relative(ROOT, result.file);
  if (result.status === 'outdated') {
    console.error(`${rel}: the services table is out of date. Run \`npm run registry:build\`.`);
    process.exit(1);
  }
  if (result.status === 'missing' || result.status === 'no-markers') {
    console.error(`${rel}: ${result.status === 'missing' ? 'not found' : 'services markers not found'}.`);
    process.exit(1);
  }
  console.log(`${rel}: services table ${result.status}.`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
